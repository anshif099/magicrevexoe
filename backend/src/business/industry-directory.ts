export type Classification = {categoryCode: string; subcategoryCode: string; businessTypeCode?: string | undefined}

export function categoryFor(code: string) {
  return Object.hasOwn(industryDirectory, code) ? industryDirectory[code] : undefined
}

export function labelsFor(classification: Classification) {
  const category = categoryFor(classification.categoryCode)
  const sub = category?.subcategories[classification.subcategoryCode]
  const business = classification.businessTypeCode && sub?.businessTypes[classification.businessTypeCode]
  return [category?.name, sub?.name, business].filter(Boolean).join(" / ")
}
